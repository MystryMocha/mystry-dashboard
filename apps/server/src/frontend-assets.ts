import fs from 'node:fs';
import path from 'node:path';
import type { FastifyInstance } from 'fastify';
import fastifyStatic from '@fastify/static';
import { panelErrorBody } from './utils/errors.js';

/** Files in the Vite output with a content hash; a content change always changes the file name, so they can be cached long-term. */
const HASHED_ASSET_CACHE_CONTROL = 'public, max-age=31536000, immutable';
/** Entry files such as index.html must be revalidated with the server every time, so new asset references are picked up right after an upgrade. */
const ENTRY_CACHE_CONTROL = 'no-cache';

export async function registerFrontendAssets(
  app: FastifyInstance,
  webDist: string,
): Promise<void> {
  if (!fs.existsSync(webDist)) return;

  const distRoot = path.resolve(webDist);
  // path.relative is case-insensitive on Windows, which is more robust than comparing string prefixes.
  const isHashedAsset = (filePath: string) =>
    path.relative(distRoot, path.resolve(filePath)).split(path.sep)[0] === 'assets';

  await app.register(fastifyStatic, {
    root: webDist,
    wildcard: true,
    // The .br / .gz copies generated by the build script are sent directly based on Accept-Encoding, falling back to the original file when missing.
    preCompressed: true,
    setHeaders(reply, filePath) {
      reply.header(
        'cache-control',
        isHashedAsset(filePath) ? HASHED_ASSET_CACHE_CONTROL : ENTRY_CACHE_CONTROL,
      );
    },
  });
  app.setNotFoundHandler((req, reply) => {
    if (req.url.startsWith('/api') || req.url.startsWith('/ws')) {
      return reply.code(404).send(panelErrorBody('server.common.notFound'));
    }
    return reply.sendFile('index.html');
  });
}
