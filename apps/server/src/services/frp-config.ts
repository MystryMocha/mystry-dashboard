import net from 'node:net';
import type { FrpTransport, TunnelMode } from '@mystry/shared';
import { PanelError } from '../utils/errors.js';

const HOSTNAME = /^(?:[a-zA-Z0-9](?:[a-zA-Z0-9-]{0,61}[a-zA-Z0-9])?)(?:\.(?:[a-zA-Z0-9](?:[a-zA-Z0-9-]{0,61}[a-zA-Z0-9])?))*$/;
const OPEN_BINDS: Record<string, true> = {
  '': true,
  '0.0.0.0': true,
  '*': true,
  '::': true,
  '::0': true,
  '127.0.0.1': true,
  localhost: true,
};

/** 写入 frpc 的字段。本地地址固定为回环，调用方不能改。 */
export interface FrpcRenderInput {
  instanceId: string;
  mode: TunnelMode;
  localPort: number;
  remotePort: number | null;
  visitorBindPort: number;
  serverAddr: string;
  serverPort: number;
  visitHost: string;
  transport: FrpTransport;
  tls: boolean;
  token: string;
  secretKey: string | null;
  tokenPath: string;
}

export function assertFrpHost(value: string): string {
  const host = value.trim();
  if (
    host.length === 0
    || host.length > 253
    || host.includes('{{')
    || host.includes('}}')
    || /[\s/\\?#@:[\]"']/.test(host)
  ) {
    throw new PanelError('server.frp.hostInvalid');
  }
  // 只接受 IPv4 字面量和主机名。上面的黑名单已拒绝 ':' 和 '['，IPv6 字面量不受支持。
  if (net.isIP(host) === 4 || HOSTNAME.test(host)) return host;
  throw new PanelError('server.frp.hostInvalid');
}

export function assertFrpToken(value: string): string {
  if (value.length === 0 || value.length > 256 || /[\u0000-\u001f\u007f]/.test(value) || value.includes('{{') || value.includes('}}')) {
    throw new PanelError('server.frp.tokenInvalid');
  }
  return value;
}

export function assertFrpName(value: string): string {
  const name = value.trim();
  if (name.length === 0 || name.length > 64 || /[\u0000-\u001f\u007f]/.test(name)) {
    throw new PanelError('server.frp.endpointNameRequired');
  }
  return name;
}

/** server-ip 指向某一块网卡时，frpc 连 127.0.0.1 会失败。 */
export function serverIpBlocksTunnel(serverIp: string | undefined): boolean {
  return !Object.prototype.hasOwnProperty.call(OPEN_BINDS, (serverIp ?? '').trim());
}

export function proxyIdentity(instanceId: string): { proxyName: string; serverName: string } {
  if (!/^[A-Za-z0-9_-]{1,100}$/.test(instanceId)) {
    throw new PanelError('server.files.instanceIdInvalid');
  }
  const proxyName = `mc-${instanceId}`;
  return { proxyName, serverName: `mystry.${proxyName}` };
}

/** host 已经过 assertFrpHost，只会是 IPv4 字面量或主机名，不需要 IPv6 方括号。 */
export function formatJoinAddress(host: string, port: number): string {
  return `${host}:${port}`;
}

function tomlString(value: string): string {
  if (/[\u0000-\u001f\u007f]/.test(value) || value.includes('{{') || value.includes('}}')) {
    throw new PanelError('server.frp.tokenInvalid');
  }
  return `"${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
}

/** 面板侧 frpc.toml。令牌放在独立文件，配置正文不出现令牌。 */
export function renderServerConfig(input: FrpcRenderInput): string {
  const { proxyName } = proxyIdentity(input.instanceId);
  assertFrpToken(input.token);
  const lines = [
    `serverAddr = ${tomlString(input.serverAddr)}`,
    `serverPort = ${input.serverPort}`,
    'user = "mystry"',
    'loginFailExit = false',
    'log.to = "console"',
    'log.level = "info"',
    'log.disablePrintColor = true',
    'auth.method = "token"',
    'auth.tokenSource.type = "file"',
    `auth.tokenSource.file.path = ${tomlString(input.tokenPath.replace(/\\/g, '/'))}`,
    `transport.protocol = ${tomlString(input.transport)}`,
    `transport.tls.enable = ${input.tls ? 'true' : 'false'}`,
    '',
    '[[proxies]]',
    `name = ${tomlString(proxyName)}`,
    'localIP = "127.0.0.1"',
    `localPort = ${input.localPort}`,
  ];
  if (input.mode === 'public') {
    if (input.remotePort === null) throw new PanelError('server.frp.remotePortRequired');
    lines.push('type = "tcp"', `remotePort = ${input.remotePort}`);
  } else {
    if (!input.secretKey) throw new PanelError('server.frp.visitorUnavailable');
    assertFrpToken(input.secretKey);
    lines.push(`type = ${tomlString(input.mode)}`, `secretKey = ${tomlString(input.secretKey)}`);
  }
  lines.push('');
  return lines.join('\n');
}

/**
 * 发给朋友的 visitor 配置。朋友用官方 frpc 打开后，在自己的 127.0.0.1 上进服。
 * 文件含穿透令牌，只应交给要一起玩的人。
 */
export function renderVisitorConfig(input: FrpcRenderInput): string {
  if (input.mode === 'public' || !input.secretKey) {
    throw new PanelError('server.frp.visitorUnavailable');
  }
  const { proxyName, serverName } = proxyIdentity(input.instanceId);
  assertFrpToken(input.token);
  assertFrpToken(input.secretKey);
  const lines = [
    '# Friend configuration generated by Mystry Dashboard.',
    '# Install official frpc, then run: frpc -c friend-frpc.toml',
    `# In Minecraft multiplayer, add server 127.0.0.1:${input.visitorBindPort}`,
    '# This file contains the tunnel token. Do not publish it.',
    `serverAddr = ${tomlString(input.serverAddr)}`,
    `serverPort = ${input.serverPort}`,
    'loginFailExit = false',
    'auth.method = "token"',
    `auth.token = ${tomlString(input.token)}`,
    `transport.protocol = ${tomlString(input.transport)}`,
    `transport.tls.enable = ${input.tls ? 'true' : 'false'}`,
    '',
    '[[visitors]]',
    `name = ${tomlString(`${proxyName}-visitor`)}`,
    `type = ${tomlString(input.mode)}`,
    `serverName = ${tomlString(serverName)}`,
    `secretKey = ${tomlString(input.secretKey)}`,
    'bindAddr = "127.0.0.1"',
    `bindPort = ${input.visitorBindPort}`,
  ];
  if (input.mode === 'xtcp') lines.push('keepTunnelOpen = true');
  lines.push('');
  return lines.join('\n');
}
